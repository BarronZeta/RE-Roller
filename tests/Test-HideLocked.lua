test('filter toggles never edit selection, original rows, history, pending requests or the running queue',function()
 local R=reset();R:Lock('T:201');R:Toggle('A:101');R:Toggle('A:102');R:Start('ability')
 local pending,queue,rows,byKey,selection,history=R.pending,R.queue,R.rows,R.byKey,R.selected,R.character.history
 local remaining=queue[1];local beforeCalls=#calls;local budget=R:Totals().ability
 R:ToggleHideLocked('ability');R:ToggleHideLocked('talent');R:ToggleHideLocked('ability')
 assert(R.running and R.pending==pending and R.queue==queue and queue[1]==remaining)
 assert(R.rows==rows and R.byKey==byKey and R.selected==selection and R.selected['A:102'])
 assert(history==R.character.history and R:Totals().ability==budget and #calls==beforeCalls and R:Locks(R.spec)['T:201'])
 R:Stop('test complete');R.pending=nil
end)
