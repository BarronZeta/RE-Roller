local function shown(p)
 local rows={};for _,b in ipairs(p.rows) do if b:IsShown() then rows[#rows+1]=b.entry end end;return rows
end
test('Hide Locked defaults off with independent controls beside each heading',function()
 local R=reset();R:Lock('A:101');R:Lock('T:201')
 for _,kind in ipairs({'ability','talent'}) do
  local p=R.window.panels[kind]
  assert(not R:IsHidingLocked(kind) and not p.hideLockedToggle:GetChecked())
  assert(p.hideLockedText:GetText()=='Hide Locked' and p.hideLockedControl.point[2]==116 and p.hideLockedControl.point[3]==-10)
  assert(#shown(p)==(kind=='ability' and 2 or 1))
 end
 assert(#calls==0)
end)
test('each Hide Locked checkbox hides only its own protected rows and preserves the locks',function()
 local R=reset();local a,t=R.window.panels.ability,R.window.panels.talent
 R:Lock('A:101');R:Lock('T:201');a.hideLockedToggle.scripts.OnClick()
 assert(R:IsHidingLocked('ability') and not R:IsHidingLocked('talent'))
 assert(#shown(a)==1 and shown(a)[1].key=='A:102' and #shown(t)==1)
 assert(a.count:GetText()=='1 / 2 shown' and t.count:GetText()=='1 learned')
 t.hideLockedToggle.scripts.OnClick();assert(#shown(t)==0 and t.empty:IsShown())
 assert(R:Locks(R.spec)['A:101'] and R:Locks(R.spec)['T:201'])
 a.hideLockedControl.scripts.OnMouseUp(a.hideLockedControl,'LeftButton')
 assert(#shown(a)==2 and a.rows[1].lock:IsShown() and R:IsHidingLocked('talent') and #calls==0)
end)
